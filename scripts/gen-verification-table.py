#!/usr/bin/env python3
"""Regenerates the generated parts of docs/verification.md (design D.9.4, WP-F3).

Two blocks of the document are generated, each between its markers:

  <!-- registry:begin --> ... <!-- registry:end -->
      the invariant registry, crates/forum-core/src/invariants/registry.rs, split by D.0.3's
      verification levels (each row's `level`): the key invariants with their executable checks,
      tests, Quint checks, the slices that check them, the slice modules that TLC runs
      (model/package.json), and their Kani harnesses; then every other invariant with its
      executable check and tests; then the Verus TODOs;
  <!-- kani:begin --> ... <!-- kani:end -->
      every #[kani::proof] function under crates/*/src, with its crate, file, unwind bound, and the
      registry rows that name it.

Each Quint name is looked up as a `val`, `def`, `run`, or `temporal` in model/**/*.qnt, each
Kani name as a #[kani::proof] function, and each test path as a file, so that a check the registry
names but nobody wrote shows as such rather than as a check (crates/forum-core/tests/registry.rs
fails on one too).

Usage:
  python3 scripts/gen-verification-table.py           rewrite docs/verification.md in place
  python3 scripts/gen-verification-table.py --check   exit 1, with a diff, if it is not current
  python3 scripts/gen-verification-table.py --print   print the two blocks

Standard library only. scripts/verify.sh runs --check, and so does CI.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "crates/forum-core/src/invariants/registry.rs"
DOC = ROOT / "docs/verification.md"
MODEL = ROOT / "model"
CRATES = ROOT / "crates"

# D.0.3 (decided on 2026-10-02): the invariants checked formally, in the order the
# registry lists them. The totality of `evolve` is the registry's `Total`. The registry's `level`
# must say the same (parse_registry checks it).
KEY = ["H1", "H2", "H3", "H4", "H5", "H6", "O1", "O2", "K1", "K3", "K4", "K5", "T1", "T2", "T3",
       "T4", "T5", "Total"]

# D.0.3: the parts of the model that check the key invariants with TLC ("the holds, keys, and time
# parts"; the time checks T3 and T4 are in every slice, T1 and T2 in holds).
KEY_SLICES = ["holds", "keys"]

BEGIN = {"registry": "<!-- registry:begin -->", "kani": "<!-- kani:begin -->"}
END = {"registry": "<!-- registry:end -->", "kani": "<!-- kani:end -->"}
NOTE = ("<!-- Generated by scripts/gen-verification-table.py; do not edit by hand. Run "
        "`python3 scripts/gen-verification-table.py` after the registry, the model, or a Kani "
        "harness changes. -->")


def fail(msg: str) -> None:
    print(f"gen-verification-table.py: {msg}", file=sys.stderr)
    sys.exit(2)


# --- The registry ---------------------------------------------------------------------------------

STRING = r'"((?:[^"\\]|\\.)*)"'


def rust_source(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    # A backslash at the end of a line inside a string literal skips the newline and the next
    # line's leading whitespace.
    return re.sub(r"\\\n\s*", "", text)


def parse_registry() -> list[dict]:
    src = rust_source(REGISTRY)
    kind_names = {"State": "state", "Step": "step", "Property": "property"}
    consts = {}
    for name, body in re.findall(r"const (\w+): &\[InvKind\] = &\[([^\]]*)\];", src):
        consts[name] = [kind_names[k] for k in re.findall(r"InvKind::(\w+)", body)]
    start = src.find("pub const INVARIANTS: &[InvariantInfo] = &[")
    if start < 0:
        fail(f"no INVARIANTS table in {REGISTRY.relative_to(ROOT)}")
    end = src.find("\n];", start)
    table = src[start:end]
    rows = []
    for block in table.split("InvariantInfo {")[1:]:
        def field(name: str, pattern: str) -> re.Match:
            m = re.search(rf"\b{name}:\s*{pattern}", block, re.S)
            if not m:
                fail(f"a registry row without {name}: {block[:80]!r}")
            return m

        def names(name: str) -> list[str]:
            return re.findall(STRING, field(name, r"&\[(.*?)\]").group(1))

        def reason(name: str) -> str | None:
            m = field(name, rf"(None|Some\(\s*{STRING}\s*,?\s*\))")
            return None if m.group(1) == "None" else m.group(2)

        kinds = field("kinds", r"(\w+)").group(1)
        if kinds not in consts:
            fail(f"unknown kinds constant {kinds}")
        rows.append({
            "id": field("id", r"Inv::(\w+)").group(1),
            "kinds": consts[kinds],
            "level": field("level", r"Level::(\w+)").group(1),
            "check": field("check", STRING).group(1),
            "tests": names("tests"),
            "quint": names("quint"),
            "quint_reason": reason("quint_reason"),
            "kani": names("kani"),
            "kani_reason": reason("kani_reason"),
            "verus": field("verus", r"VerusStatus::(\w+)").group(1),
            "verus_todo": field("verus_todo", STRING).group(1),
        })
    if not rows:
        fail("the registry has no rows")
    ids = [r["id"] for r in rows]
    for k in KEY:
        if k not in ids:
            fail(f"the key invariant {k} has no registry row")
    for r in rows:
        if (r["level"] == "Key") != (r["id"] in KEY):
            fail(f"{r['id']}: the registry's level {r['level']} is not D.0.3's")
    return rows


# --- The model ------------------------------------------------------------------------------------

def qnt_files() -> list[Path]:
    skip = {"node_modules", "traces", "_apalache-out"}
    return sorted(p for p in MODEL.rglob("*.qnt") if not skip & set(p.relative_to(MODEL).parts))


def model_index() -> tuple[dict[str, str], dict[str, list[str]]]:
    """Where each name is defined (its first file), and the slices whose files mention it."""
    defined: dict[str, str] = {}
    mentioned: dict[str, list[str]] = {}
    for path in qnt_files():
        text = path.read_text(encoding="utf-8")
        rel = path.relative_to(MODEL).as_posix()
        for name in re.findall(r"\b(?:val|def|run|temporal)\s+([A-Za-z_]\w*)", text):
            defined.setdefault(name, rel)
        if path.parent.name == "slices":
            code = re.sub(r"/\*.*?\*/|//[^\n]*", " ", text, flags=re.S)
            for name in set(re.findall(r"\b([A-Za-z_]\w*)\b", code)):
                mentioned.setdefault(name, []).append(path.stem)
    return defined, mentioned


def slice_names() -> list[str]:
    return sorted(p.stem for p in (MODEL / "slices").glob("*.qnt") if p.stem != "common")


def tlc_modules() -> list[str]:
    scripts = json.loads((MODEL / "package.json").read_text(encoding="utf-8")).get("scripts", {})
    return sorted(s.split(":", 1)[1] for s in scripts if s.startswith("tlc:"))


def slices_of(name: str, mentioned: dict[str, list[str]]) -> list[str]:
    files = mentioned.get(name, [])
    if "common" in files:
        return slice_names()
    return sorted(f for f in files if f != "common")


# --- Kani -----------------------------------------------------------------------------------------

def kani_harnesses() -> list[dict]:
    out = []
    for path in sorted(CRATES.glob("*/src/**/*.rs")):
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            if line.strip() != "#[kani::proof]":
                continue
            unwind = ""
            for nxt in lines[i + 1:i + 12]:
                m = re.search(r"#\[kani::unwind\((\d+)\)\]", nxt)
                if m:
                    unwind = m.group(1)
                m = re.match(r"\s*(?:pub(?:\([^)]*\))?\s+)?fn\s+(\w+)", nxt)
                if m:
                    out.append({
                        "name": m.group(1),
                        "crate": path.relative_to(CRATES).parts[0],
                        "file": path.relative_to(ROOT).as_posix(),
                        "unwind": unwind,
                    })
                    break
            else:
                fail(f"a #[kani::proof] without a function in {path.relative_to(ROOT)}:{i + 1}")
    return sorted(out, key=lambda h: (h["crate"], h["file"], h["name"]))


# --- Rendering ------------------------------------------------------------------------------------

def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def code_list(items: list[str], missing: set[str], missing_word: str) -> str:
    return ", ".join(f"`{n}`" + (f" ({missing_word})" if n in missing else "") for n in items)


def kinds_text(kinds: list[str]) -> str:
    return " and ".join(kinds)


def test_list(paths: list[str]) -> str:
    """The test files, shown under crates/forum-core unless another crate is named; a path that
    is not a file is marked."""
    def short(p: str) -> str:
        shown = p.removeprefix("crates/forum-core/").removeprefix("crates/")
        return f"`{shown}`" + ("" if (ROOT / p).is_file() else " (*missing*)")
    return ", ".join(short(p) for p in paths)


def registry_block(rows: list[dict]) -> str:
    defined, mentioned = model_index()
    harnesses = {h["name"] for h in kani_harnesses()}
    modules = tlc_modules()
    missing_q = {n for r in rows for n in r["quint"] if n not in defined}
    missing_k = {n for r in rows for n in r["kani"] if n not in harnesses}

    out = [BEGIN["registry"], NOTE, "",
           "Every executable check runs after every call and firing in every test (`World`), in "
           "the property test, in the §32 scenario, in debug builds of the server, and in "
           "`forum-server check` (D.9.1). The tests column names the files whose tests exercise "
           "the invariant by name (under `crates/forum-core` unless a crate is named): the "
           "mutations its check must reject, and the flows that reach it.", "",
           "**The key invariants (D.0.3).** Each has its executable check and tests, the model's "
           "checks in the slices named, TLC on the modules of D.0.3's slices "
           "(`npm run tlc:<module>`), Kani harnesses, and a Verus TODO. A name marked *not in the "
           "model* or *not written* is one the registry names that does not exist.", "",
           "| Invariant | Kind | Executable check | Tests | Quint | Slices | TLC modules | Kani | "
           "Verus |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["id"] not in KEY:
            continue
        sl = sorted({s for n in r["quint"] for s in slices_of(n, mentioned)})
        elsewhere = sorted({defined[n] for n in r["quint"] if n in defined
                            and not slices_of(n, mentioned)})
        slices = ", ".join(sl + [f"`{f}`" for f in elsewhere]) or "none"
        tlc = ", ".join(f"`{m}`" for m in modules
                        if any(m.startswith(s + "_") for s in sl if s in KEY_SLICES)) or "none"
        quint = code_list(r["quint"], missing_q, "*not in the model*") or \
            f"none: *{r['quint_reason']}*"
        kani = code_list(r["kani"], missing_k, "*not written*") or \
            f"none: *{r['kani_reason']}*"
        out.append(f"| {r['id']} | {kinds_text(r['kinds'])} | {cell(r['check'])} | "
                   f"{cell(test_list(r['tests']))} | {cell(quint)} | {cell(slices)} | {cell(tlc)} "
                   f"| {cell(kani)} | V-{r['id']}, {r['verus'].lower()} |")

    out += ["",
            "**The other invariants (D.0.3).** Each is checked by its executable check and its "
            "tests (the registry's level *tests*); D.0.3 asks no Quint or Kani work of them. The "
            "last column names the Quint checks and Kani harnesses that exist for them all the "
            "same, and the reasons where none does.", "",
            "| Invariant | Kind | Executable check | Tests | Quint and Kani (not required) |",
            "|---|---|---|---|---|"]
    for r in rows:
        if r["id"] in KEY:
            continue
        parts = []
        if r["quint"]:
            parts.append("Quint " + code_list(r["quint"], missing_q, "*not in the model*"))
        if r["quint_reason"]:
            parts.append(f"no Quint: *{r['quint_reason']}*" if not r["quint"]
                         else f"no Quint for the rest: *{r['quint_reason']}*")
        if r["kani"]:
            parts.append("Kani " + code_list(r["kani"], missing_k, "*not written*"))
        if r["kani_reason"]:
            parts.append(f"no Kani: *{r['kani_reason']}*")
        out.append(f"| {r['id']} | {kinds_text(r['kinds'])} | {cell(r['check'])} | "
                   f"{cell(test_list(r['tests']))} | {cell('; '.join(parts))} |")

    def todos(level: str) -> list[str]:
        lines = []
        for r in rows:
            if r["level"] == level:
                label, _, text = r["verus_todo"].partition(":")
                lines.append(f"- **{label}** ({r['verus'].lower()}):{text}")
        return lines

    out += ["", "**Verus TODOs** (D.9.4, D.13.4: after the first release, an optional step for "
            "the key invariants, D.0.3). Every row starts at *todo*.", ""]
    out += todos("Key")
    out += ["", "The other rows keep their TODOs in the registry, which D.0.3 no longer "
            "requires:", ""]
    out += todos("Tests")
    out.append(END["registry"])
    return "\n".join(out)


def kani_block(rows: list[dict]) -> str:
    by_name: dict[str, list[str]] = {}
    for r in rows:
        for n in r["kani"]:
            by_name.setdefault(n, []).append(r["id"])
    hs = kani_harnesses()
    written = {h["name"] for h in hs}
    out = [BEGIN["kani"], NOTE, "",
           f"{len(hs)} harnesses are written. *Scope* is *key* when a key invariant's registry row "
           "names the harness, *other* when only other rows do, and *not in the registry* "
           "otherwise (the primitives D.12.5 lists under the key invariants, and harnesses that "
           "D.9.2 names but the registry does not).", "",
           "| Harness | Crate | File | Unwind | Registry rows | Scope |",
           "|---|---|---|---|---|---|"]
    for h in hs:
        ids = by_name.get(h["name"], [])
        scope = ("key" if any(i in KEY for i in ids) else "other") if ids else "not in the registry"
        out.append(f"| `{h['name']}` | {h['crate']} | `{h['file']}` | {h['unwind'] or '-'} | "
                   f"{', '.join(ids) or '-'} | {scope} |")
    unwritten = [(n, ids) for n, ids in by_name.items() if n not in written]
    if unwritten:
        out += ["", "Named in the registry but not written (marked when a key invariant's row "
                "names it):", ""]
        for n, ids in sorted(unwritten):
            key = " **(key)**" if any(i in KEY for i in ids) else ""
            out.append(f"- `{n}`: {', '.join(ids)}{key}")
    out.append(END["kani"])
    return "\n".join(out)


def render(doc: str, blocks: dict[str, str]) -> str:
    for name, block in blocks.items():
        b, e = BEGIN[name], END[name]
        i, j = doc.find(b), doc.find(e)
        if i < 0 or j < 0 or j < i:
            fail(f"{DOC.relative_to(ROOT)} lacks the markers {b} and {e}")
        doc = doc[:i] + block + doc[j + len(e):]
    return doc


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="fail if docs/verification.md is stale")
    group.add_argument("--print", action="store_true", help="print the generated blocks")
    args = ap.parse_args()

    rows = parse_registry()
    blocks = {"registry": registry_block(rows), "kani": kani_block(rows)}
    if args.print:
        print(blocks["registry"])
        print()
        print(blocks["kani"])
        return 0
    old = DOC.read_text(encoding="utf-8")
    new = render(old, blocks)
    if args.check:
        if new == old:
            print(f"{DOC.relative_to(ROOT)}: the generated tables are current "
                  f"({len(rows)} registry rows, {len(kani_harnesses())} Kani harnesses)")
            return 0
        sys.stdout.writelines(difflib.unified_diff(
            old.splitlines(keepends=True), new.splitlines(keepends=True),
            "docs/verification.md", "docs/verification.md (regenerated)"))
        print(f"\n{DOC.relative_to(ROOT)} is stale: run python3 scripts/gen-verification-table.py")
        return 1
    if new != old:
        DOC.write_text(new, encoding="utf-8")
        print(f"rewrote {DOC.relative_to(ROOT)}")
    else:
        print(f"{DOC.relative_to(ROOT)} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
